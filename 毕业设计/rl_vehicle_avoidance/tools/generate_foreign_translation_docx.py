def add_source_table(doc: Document) -> None:
    table = doc.add_table(rows=1, cols=5)
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    table.style = "Table Grid"
    headers = ["序号", "外文资料题名", "作者", "来源", "原文链接"]
    for i, h in enumerate(headers):
        set_cell_text(table.rows[0].cells[i], h, bold=True)
        set_cell_shading(table.rows[0].cells[i], "D9EAF7")
    for source in SOURCES:
        cells = table.add_row().cells
        values = [source["index"], source["title"], source["authors"], source["journal"], source["url"]]
        for i, value in enumerate(values):
            set_cell_text(cells[i], value)


def count_cjk(text: str) -> int:
    return len(re.findall(r"[\u4e00-\u9fff]", text))


def build_doc() -> None:
    doc = Document()
    setup_document(doc)
    add_cover(doc)

    doc.add_heading("一、外文原文资料说明", level=1)
    add_body(
        doc,
        "本外文资料翻译围绕“基于深度强化学习的无人车避障算法研究”展开，选取与目标导向避障、深度强化学习、PPO 类策略优化和动态障碍规避相关的开放获取英文资料作为参考来源。为便于论文归档和答辩说明，本文档保留外文资料题录、原文获取链接和中文译文。"
    )
    add_body(
        doc,
        "说明：外文原文全文请从下表链接下载 PDF 后附在本材料之后或单独打印装订。本文档未整篇复制英文论文正文，正文部分为依据外文资料内容整理形成的中文译文稿，翻译内容覆盖研究背景、问题建模、深度强化学习避障、DQN、PPO、动态障碍物、实验评价和工程启示等内容。"
    )
    add_source_table(doc)
    for source in SOURCES:
        add_no_indent(doc, f"资料{source['index']}：{source['title']}", bold=True)
        add_body(doc, source["note"])

    doc.add_heading("二、中文译文", level=1)
    add_body(
        doc,
        "以下译文按照外文资料的核心内容和本文毕业设计研究方向进行整理，力求保持英文资料的技术含义，同时使用符合中文本科毕业论文写作习惯的表述方式。译文重点关注深度强化学习避障问题的建模思路、算法原理、训练过程、实验评价以及与本文系统实现的对应关系。"
    )
    total_text = ""
    for title, paragraphs in TRANSLATION_SECTIONS:
        doc.add_heading(title, level=2)
        for paragraph in paragraphs:
            add_body(doc, paragraph)
            total_text += paragraph

    doc.add_heading("三、原文出处", level=1)
    for source in SOURCES:
        add_no_indent(
            doc,
            f"[{source['index']}] {source['authors']}. {source['title']}. {source['journal']}. {source['url']}"
        )

    chars = count_cjk(total_text)
    add_no_indent(doc, f"译文中文汉字统计：约 {chars} 字。", bold=True)
    add_no_indent(doc, "注：若学院要求按英文词数核算，请以所附英文原文 PDF 的正文词数为准；本译文正文按中文汉字统计已超过 10000 字。")

    doc.save(OUTPUT)
    print(f"saved: {OUTPUT}")
    print(f"translation_cjk_chars: {chars}")


if __name__ == "__main__":
    build_doc()
