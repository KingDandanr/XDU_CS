def clear_document(doc: Document) -> None:
    body = doc._body._element
    for child in list(body):
        if child.tag.endswith("sectPr"):
            continue
        body.remove(child)


def set_section_layout(doc: Document) -> None:
    for section in doc.sections:
        section.top_margin = Cm(3)
        section.bottom_margin = Cm(2)
        section.left_margin = Cm(3)
        section.right_margin = Cm(2)
        section.header_distance = Cm(2)
        section.footer_distance = Cm(1)


def set_default_styles(doc: Document) -> None:
    normal = doc.styles["Normal"]
    normal.font.name = "宋体"
    normal.font.size = Pt(12)
    normal.paragraph_format.first_line_indent = Pt(24)
    normal.paragraph_format.line_spacing = 1.5
    normal.paragraph_format.space_after = Pt(0)

    if "Title" in doc.styles:
        style = doc.styles["Title"]
        style.font.name = "黑体"
        style.font.size = Pt(16)
        style.paragraph_format.first_line_indent = Pt(0)
        style.paragraph_format.alignment = WD_ALIGN_PARAGRAPH.CENTER

    for name in ("Heading 2", "Heading 3"):
        if name in doc.styles:
            style = doc.styles[name]
            style.font.name = "宋体"
            style.font.size = Pt(14 if name == "Heading 2" else 12)
            style.paragraph_format.first_line_indent = Pt(0)
            style.paragraph_format.alignment = WD_ALIGN_PARAGRAPH.CENTER if name == "Heading 2" else WD_ALIGN_PARAGRAPH.LEFT


def add_center(doc: Document, text: str, style: str = "Normal", bold: bool = False, size: int | None = None) -> None:
    p = doc.add_paragraph(style=style)
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.first_line_indent = Pt(0)
    r = p.add_run(text)
    r.bold = bold
    if size:
        r.font.size = Pt(size)


def add_body(doc: Document, text: str) -> None:
    p = doc.add_paragraph(style="Normal")
    p.paragraph_format.first_line_indent = Pt(24)
    p.paragraph_format.line_spacing = 1.5
    p.add_run(text)


def add_formula(doc: Document, text: str) -> None:
    p = doc.add_paragraph(style="Normal")
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.first_line_indent = Pt(0)
    p.paragraph_format.line_spacing = 1.5
    run = p.add_run(text)
    run.font.name = "Times New Roman"
    run.font.size = Pt(12)


def add_heading(doc: Document, text: str, level: int) -> None:
    if level == 1:
        p = doc.add_paragraph(style="Title")
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    elif level == 2:
        p = doc.add_paragraph(style="Heading 2")
    else:
        p = doc.add_paragraph(style="Heading 3")
    p.paragraph_format.first_line_indent = Pt(0)
    p.add_run(text)


def add_table(doc: Document, rows: list[list[str]], caption: str | None = None) -> None:
    if caption:
        p = doc.add_paragraph(style="Caption")
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        p.add_run(caption)
    table = doc.add_table(rows=len(rows), cols=len(rows[0]))
    table.style = "Table Grid"
    for i, row in enumerate(rows):
        for j, value in enumerate(row):
            cell = table.cell(i, j)
            cell.text = value
            for paragraph in cell.paragraphs:
                paragraph.paragraph_format.first_line_indent = Pt(0)
                paragraph.paragraph_format.line_spacing = 1.2
                for run in paragraph.runs:
                    run.font.name = "宋体"
                    run.font.size = Pt(10.5)
                    if i == 0:
                        run.bold = True
    doc.add_paragraph()


def add_picture_if_exists(doc: Document, path: Path, caption: str) -> None:
    if not path.exists():
        return
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.first_line_indent = Pt(0)
    p.add_run().add_picture(str(path), width=Cm(12.5))
    c = doc.add_paragraph(style="Caption")
    c.alignment = WD_ALIGN_PARAGRAPH.CENTER
    c.paragraph_format.first_line_indent = Pt(0)
    c.add_run(caption)


def add_list(doc: Document, items: list[str]) -> None:
    for item in items:
        p = doc.add_paragraph(style="Normal")
        p.paragraph_format.first_line_indent = Pt(0)
        p.paragraph_format.left_indent = Pt(24)
        p.add_run(item)


