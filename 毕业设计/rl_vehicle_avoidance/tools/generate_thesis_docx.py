def draw_flowchart(path: Path, title: str, labels: list[str]) -> None:
    ASSET_DIR.mkdir(parents=True, exist_ok=True)
    font_path = choose_chinese_font()
    title_font = ImageFont.truetype(font_path, 34) if font_path else ImageFont.load_default()
    label_font = ImageFont.truetype(font_path, 23) if font_path else ImageFont.load_default()

    image = Image.new("RGB", (1400, 520), "white")
    draw = ImageDraw.Draw(image)
    title_box = draw.textbbox((0, 0), title, font=title_font)
    draw.text(((1400 - (title_box[2] - title_box[0])) / 2, 35), title, fill="#1f2933", font=title_font)

    box_w, box_h = 210, 110
    y = 230
    xs = [110, 370, 630, 890, 1150]
    for idx, (x, label) in enumerate(zip(xs, labels)):
        rect = (x, y, x + box_w, y + box_h)
        draw.rounded_rectangle(rect, radius=18, fill="#e8f1f2", outline="#2f4f4f", width=3)
        lines = label.split("\n")
        line_heights = [draw.textbbox((0, 0), line, font=label_font)[3] for line in lines]
        total_h = sum(line_heights) + (len(lines) - 1) * 8
        text_y = y + (box_h - total_h) / 2 - 2
        for line in lines:
            text_box = draw.textbbox((0, 0), line, font=label_font)
            text_w = text_box[2] - text_box[0]
            draw.text((x + (box_w - text_w) / 2, text_y), line, fill="#1f2933", font=label_font)
            text_y += (text_box[3] - text_box[1]) + 8

        if idx < len(xs) - 1:
            start = (x + box_w + 18, y + box_h / 2)
            end = (xs[idx + 1] - 18, y + box_h / 2)
            draw.line((start, end), fill="#2f4f4f", width=4)
            arrow = [
                (end[0], end[1]),
                (end[0] - 18, end[1] - 10),
                (end[0] - 18, end[1] + 10),
            ]
            draw.polygon(arrow, fill="#2f4f4f")

    image.save(path)


